<?php

namespace ByJG\Scriptify;

use ByJG\JinjaPhp\Template;

class Scriptify
{
    protected static ?ServiceWriter $writer = null;

    public static function setWriter(?ServiceWriter $writer): void
    {
        self::$writer = $writer;
    }

    public static function getWriter(): ?ServiceWriter
    {
        if (self::$writer == null) {
            self::$writer = new ServiceWriter();
        }

        return self::$writer;
    }

    /**
     * Install a service that runs a class method through the bundled `scriptify run`.
     *
     * The command is written in full, every option resolved: the PHP binary, the absolute
     * root directory, the bootstrap (the autoload file), the class and its arguments. The
     * service does not depend on any default at run time.
     *
     * @throws \Exception
     */
    public static function install(
        $svcName,
        $className,
        $bootstrap,
        $curdir,
        $template,
        $description,
        $consoleArgs,
        $environment,
        $check = true
    ): bool
    {
        $realpathCurdir = realpath($curdir);
        if (($realpathCurdir === false || !file_exists($realpathCurdir)) && $check) {
            throw new \Exception("RootPath '" . $curdir . "' not found. Use an absolute path. e.g. /projects/example");
        }

        if (!file_exists($curdir . '/' . $bootstrap) && $check) {
            throw new \Exception("Bootstrap '$bootstrap' not found. Use a relative path from root directory. e.g. vendor/autoload.php");
        }

        // Normalise before the command is built, so the installed service file always
        // carries the canonical backslash form -- whichever spelling the person typed.
        $classNameStr = Runner::normalize(is_string($className) ? $className : (string)$className);

        // Check if is OK
        if ($check) {
            // Reflection only: the question here is whether the class and the
            // method exist, and method_exists() answers it from the class name.
            // Building the object would drag in its whole dependency graph --
            // opening database connections and the like -- to install a service
            // that has not run yet.
            require_once($bootstrap);

            $classParts = explode('::', $classNameStr);
            if (!class_exists($classParts[0])) {
                throw new \Exception('Could not find class ' . $classParts[0]);
            }
            if (!isset($classParts[1]) || !method_exists($classParts[0], $classParts[1])) {
                throw new \Exception('Could not find method ' . $classNameStr);
            }
        }

        $command = PHP_BINARY . ' ' . (string)realpath(__DIR__ . "/../scripts/scriptify")
            . ' run "' . str_replace("\\", "\\\\", $classNameStr) . '"'
            . ' --bootstrap "' . $bootstrap . '"'
            . ' --rootdir "' . (string)$realpathCurdir . '"';
        foreach ((array)$consoleArgs as $arg) {
            $command .= ' --arg ' . escapeshellarg((string)$arg);
        }

        return self::installCommand(
            (string)$svcName,
            $command,
            (string)$realpathCurdir,
            (string)$template,
            (string)$description,
            (array)$environment
        );
    }

    /**
     * Install a service that runs a command line. The command must understand `--daemon`
     * (run again and again) for every template but crond, which runs it once a minute.
     *
     * This is what install() uses for `scriptify run`, and what an application with its own
     * command line uses to install one of its commands: the command is written as given.
     *
     * @param string $command The full command line, every path absolute.
     * @param string $rootPath The working directory of the service.
     * @param array<string, string|int|float|bool> $environment Variables for the service.
     * @throws \Exception
     */
    public static function installCommand(
        string $svcName,
        string $command,
        string $rootPath,
        string $template = 'systemd',
        string $description = 'Service generated by Scriptify',
        array $environment = []
    ): bool {
        $targetPathAvailable = [
            'initd' => "/etc/init.d/$svcName",
            'crond' => "/etc/cron.d/$svcName",
            'upstart' => "/etc/init/$svcName.conf",
            'systemd' => "/etc/systemd/system/$svcName.service"
        ];
        if (!isset($targetPathAvailable[$template])) {
            throw new \Exception(
                "Template $template does not exists. Available templates are: "
                . implode(',', array_keys($targetPathAvailable))
            );
        }

        $targetServicePath = $targetPathAvailable[$template];
        $templatePath = __DIR__ . "/../template/linux-" . $template . "-service.jinja";

        if (!file_exists($templatePath)) {
            throw new \Exception("Template '$templatePath' not found");
        }

        $environmentPrepared = '/etc/scriptify/' . $svcName . '.env';

        $vars = [
            'description' => $description,
            'command' => $command,
            'svcname' => $svcName,
            'rootpath' => $rootPath,
            'environment' => $environmentPrepared,
            'envcmdline' => implode(
                ' ',
                array_map(
                    /**
                     * @param mixed $v
                     * @param string $k
                     * @return string
                     */
                    function ($v, $k) {
                        return "$k=\"$v\"";
                    },
                    $environment,
                    array_keys($environment)
                )
            )
        ];

        $templateContent = file_get_contents($templatePath);
        if ($templateContent === false) {
            throw new \Exception("Could not read template file: $templatePath");
        }
        $templateObj = new Template($templateContent);
        $templateResult = $templateObj->render($vars);
        if (!is_string($templateResult)) {
            throw new \Exception("Template rendering failed - expected string, got " . gettype($templateResult));
        }

        $writer = Scriptify::getWriter();
        if ($writer === null) {
            throw new \Exception('Writer not initialized');
        }
        $writer->writeEnvironment($environmentPrepared, $environment);
        $writer->writeService($targetServicePath, $templateResult, $template == 'initd' ? 0755 : null);

        return true;
    }

    /**
     * @throws ScriptifyException
     */
    public static function uninstall(string $svcName): void
    {
        $list = [
            "/etc/init.d/$svcName",
            "/etc/init/$svcName.conf",
            "/etc/systemd/system/$svcName.service",
            '/etc/scriptify/' . $svcName . '.env',
            '/etc/cron.d/' . $svcName,
        ];

        $found = false;
        foreach ($list as $service) {
            if (file_exists($service)) {
                $found = true;
                if (strpos($service, ".env") === false && !self::isScriptifyService($service)) {
                    throw new ScriptifyException("Service '$svcName' was not created by Scriptify");
                }
                unlink($service);
            }
        }

        if (!$found) {
            throw new ScriptifyException("Service '$svcName' does not exists");
        }

        restore_error_handler();
    }

    protected static function isScriptifyService(string $filename): bool
    {
        set_error_handler(function ($number, $error) {
            throw new \Exception($error);
        });

        if (!file_exists($filename)) {
            return false;
        }
        $contents = file_get_contents($filename);
        if ($contents === false) {
            return false;
        }

        return (str_contains($contents, 'PHP_SCRIPTIFY'));
    }

    public static function listServices(): array
    {
        $list = [
            "initd" => glob("/etc/init.d/*"),
            "crond" => glob("/etc/cron.d/*"),
            "upstart" => glob("/etc/init/*.conf"),
            "systemd" => glob("/etc/systemd/system/*.service")
        ];
        $return = [];

        foreach ($list as $svcType => $filenames) {
            if ($filenames === false) {
                continue;
            }
            foreach ($filenames as $filename) {
                if (self::isScriptifyService($filename)) {
                    $return[] = $svcType . ": " . 
                        str_replace(
                        '.service',
                        '',
                        str_replace(
                            '.conf',
                            '',
                            basename($filename)
                        )
                    );
                }
            }
        }

        return $return;
    }

}
